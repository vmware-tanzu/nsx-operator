#!/usr/bin/env bash

set -o errexit
set -o nounset
set -o pipefail

SCRIPT_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
OUTPUT_PKG=github.com/vmware-tanzu/nsx-operator/pkg/client
APIS_ROOT="${SCRIPT_ROOT}/pkg/apis"
CLIENT_ROOT="${SCRIPT_ROOT}/pkg/client"
BOILERPLATE="${SCRIPT_ROOT}/hack/boilerplate.go.txt"
export GOBIN="${GOBIN:-$(go env GOPATH)/bin}"

# Generate only the public VPC and migration APIs, excluding legacy/EAS APIs.
# Install pinned generators before loading types from the separate API module.
for generator in client-gen lister-gen informer-gen; do
    go install "k8s.io/code-generator/cmd/${generator}@v0.35.1"
done

cd "${APIS_ROOT}"
API_PACKAGES=(
    github.com/vmware-tanzu/nsx-operator/pkg/apis/vpc/v1alpha1
    github.com/vmware-tanzu/nsx-operator/pkg/apis/migration/v1alpha1
)

# Remove obsolete generated resources when a kind moves between API groups.
find "${CLIENT_ROOT}/clientset" "${CLIENT_ROOT}/informers" "${CLIENT_ROOT}/listers" \
    -name '*.go' -exec grep -l '^// Code generated by .*gen. DO NOT EDIT.$' {} + | xargs rm -f

"${GOBIN}/client-gen" --go-header-file "${BOILERPLATE}" \
    --output-dir "${CLIENT_ROOT}/clientset" --output-pkg "${OUTPUT_PKG}/clientset" \
    --clientset-name versioned --input-base github.com/vmware-tanzu/nsx-operator/pkg/apis \
    --input vpc/v1alpha1 --input migration/v1alpha1
"${GOBIN}/lister-gen" --go-header-file "${BOILERPLATE}" \
    --output-dir "${CLIENT_ROOT}/listers" --output-pkg "${OUTPUT_PKG}/listers" \
    "${API_PACKAGES[@]}"
"${GOBIN}/informer-gen" --go-header-file "${BOILERPLATE}" \
    --output-dir "${CLIENT_ROOT}/informers" \
    --output-pkg "${OUTPUT_PKG}/informers" \
    --versioned-clientset-package "${OUTPUT_PKG}/clientset/versioned" \
    --listers-package "${OUTPUT_PKG}/listers" "${API_PACKAGES[@]}"

cd "${CLIENT_ROOT}"
go mod tidy
